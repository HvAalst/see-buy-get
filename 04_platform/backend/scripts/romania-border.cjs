// ROMANIA'S BORDER, for the GPS watch of RO e-Transport (2026-11-24; corridor compliance, slice 3; the owner's brief, feature 4:
// "automatically switch ro_transit_status to ACTIVE_IN_RO when coordinates enter Romania"): writes
// src/modules/pudo/romania-border.ts. Run by hand, never by the pipeline, after `nest build` (it reads the server's own geometry
// from dist). First download, into an empty folder of its own (data, never code):
//   rou-ADM0.geojson  geoBoundaries gbOpen ROU ADM0, full: Romania's outline (StatSilk, 2018; CC BY 3.0, to be credited)
//                     from https://www.geoboundaries.org/api/current/gbOpen/ROU/ADM0/ → gjDownloadURL. Not the simplified file: it
//                     cuts the Black Sea coast, and put Constanța outside Romania.
// then: node scripts/romania-border.cjs <that folder>
const fs = require('fs');
const path = require('path');
const G = require('../dist/modules/pudo/zone-geometry.js');
const DATA = process.argv[2];
if (!DATA) throw new Error('usage: node scripts/romania-border.cjs <folder with rou-ADM0.geojson>');
const OUT = path.join(__dirname, '../src/modules/pudo/romania-border.ts');
const areas = G.parseAreaFile(fs.readFileSync(path.join(DATA, 'rou-ADM0.geojson'), 'utf8'), 'shapeName');
// Within this of the line counts as Romania: the outline's coast is up to about 400 m off (Mamaia), and the nearest
// neighbouring towns measured are over 1 km beyond it (Ungheni, Csanádpalota).
const NEAR_KM = 0.5;
const inRo = (p) => G.contains(areas[0].shape, p) || G.distanceKm(areas[0].shape, p) <= NEAR_KM;
if (areas.length !== 1 || areas[0].name !== 'Romania') throw new Error(`expected Romania alone, got ${areas.map((a) => a.name).join(', ')}`);
const shape = areas[0].shape;
const encoded = shape.map((p) => G.encodePolygon(p));
const corners = shape.reduce((n, p) => n + p.reduce((m, r) => m + r.length, 0), 0);
// The check the file must pass before it is written: towns on each side of the border, near it.
const shouldBe = [
  ['Bucharest', 44.4268, 26.1025, true],
  ['Giurgiu', 43.9037, 25.9699, true],
  ['Arad', 46.1866, 21.3123, true],
  ['Constanța', 44.1598, 28.6348, true],
  ['Mamaia', 44.25, 28.62, true],
  ['Sulina', 45.158, 29.653, true],
  ['Siret', 47.95, 26.06, true],
  ['Ruse (BG)', 43.8356, 25.9657, false],
  ['Vidin (BG)', 43.9962, 22.8679, false],
  ['Szeged (HU)', 46.253, 20.1414, false],
  ['Chișinău (MD)', 47.0105, 28.8638, false],
  ['Belgrade (RS)', 44.7866, 20.4489, false],
  ['Csanádpalota (HU)', 46.24, 20.73, false],
  ['Ungheni (MD)', 47.21, 27.8, false],
  ['Porubne (UA)', 48.0, 26.05, false],
  ['Durankulak (BG)', 43.69, 28.53, false],
];
for (const [name, lat, lng, inside] of shouldBe) {
  if (inRo({ lat, lng }) !== inside) throw new Error(`${name} should be ${inside ? 'inside' : 'outside'} Romania`);
}
const body = `/**
 * ROMANIA'S BORDER (2026-11-24; corridor compliance, slice 3; the owner's brief, feature 4): the outline the GPS watch of RO
 * e-Transport reads, to tell a vehicle in Romania from one outside it. Generated by backend/scripts/romania-border.cjs from
 * geoBoundaries gbOpen ROU ADM0 (StatSilk, 2018; licensed CC BY 3.0: "geoBoundaries, StatSilk"): ${shape.length} polygons,
 * ${corners} corners. Its coast is up to about 400 m off, so a reading within ${NEAR_KM * 1000} m of the line counts as Romania: the
 * nearest neighbouring towns measured lie over 1 km beyond it, and a truck on the Bulgarian end of the Giurgiu–Ruse bridge
 * reads as in Romania. The watch asks three readings outside before it calls a vehicle out of Romania.
 */
import { contains, decodePolygon, distanceKm, type Shape } from './zone-geometry';

const ENCODED: readonly string[] = ${JSON.stringify(encoded, null, 2)};

/** Romania's outline, decoded once. */
export const ROMANIA_BORDER: Shape = ENCODED.map(decodePolygon);

/** How near the line still counts as Romania, in km. */
export const ROMANIA_NEAR_KM = ${NEAR_KM};

/** Whether a point is in Romania: inside the outline, or within ROMANIA_NEAR_KM of it. */
export function insideRomania(point: { lat: number; lng: number }): boolean {
  return contains(ROMANIA_BORDER, point) || distanceKm(ROMANIA_BORDER, point) <= ROMANIA_NEAR_KM;
}

/** How far a point is from Romania, in km: 0 inside it. */
export function kmFromRomania(point: { lat: number; lng: number }): number {
  return distanceKm(ROMANIA_BORDER, point);
}
`;
fs.writeFileSync(OUT, body);
console.log(`wrote ${OUT}: ${shape.length} polygons, ${corners} corners; ${shouldBe.length} towns on the right side`);
